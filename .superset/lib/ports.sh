# Per-workspace port reservation. Requires lib/common.sh.
#
# Reservations live in $ALLOC_DIR/<workspace-key> (one file per workspace holding
# its base port) so parallel workspaces never pick the same block. The block is:
#   base+0  APP_PORT  (Django / web dev server)
#   base+1  DB_PORT   (Postgres published on the host)
#   base+2  WEB_PORT  (spare: future Next.js app)
#   base+3.. spare

_block_taken() {
  local base=$1 f p
  for f in "$ALLOC_DIR"/*; do
    [ -f "$f" ] || continue
    [ "$f" = "$ALLOC_FILE" ] && continue
    [ "$(cat "$f")" = "$base" ] && return 0
  done
  for p in $(seq "$base" $((base + PORT_BLOCK - 1))); do
    port_in_use "$p" && return 0
  done
  return 1
}

_reserve() {
  mkdir -p "$ALLOC_DIR"
  if [ -f "$ALLOC_FILE" ]; then
    BASE_PORT="$(cat "$ALLOC_FILE")"
    return 0
  fi
  local i base
  for i in $(seq 0 $((PORT_MAX_BLOCKS - 1))); do
    base=$((PORT_BASE_START + i * PORT_BLOCK))
    if ! _block_taken "$base"; then
      echo "$base" > "$ALLOC_FILE"
      BASE_PORT="$base"
      return 0
    fi
  done
  echo "No free port block found in $ALLOC_DIR" >&2
  return 1
}

reserve_ports() {
  with_lock _reserve || return 1
  APP_PORT=$BASE_PORT
  DB_PORT=$((BASE_PORT + 1))
  WEB_PORT=$((BASE_PORT + 2))
  cat > "$PORTS_ENV" <<EOT
# Generated by .superset/setup.sh — per-workspace ports. Do not commit.
BASE_PORT=$BASE_PORT
APP_PORT=$APP_PORT
PORT=$APP_PORT
DB_PORT=$DB_PORT
WEB_PORT=$WEB_PORT
COMPOSE_PROJECT_NAME=$COMPOSE_PROJECT_NAME
EOT
  export APP_PORT PORT="$APP_PORT" DB_PORT WEB_PORT BASE_PORT
}

release_ports() {
  with_lock rm -f "$ALLOC_FILE"
  rm -f "$PORTS_ENV"
}
